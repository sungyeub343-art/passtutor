async function generate() {
  const expectedRoots = new Set(regions.map(({ slug }) => slug));
  const existingRoots = ["seoul", "busan", "daegu", "incheon", "gwangju", "jeonnam", "gwangju-jeonnam", "daejeon", "ulsan", "sejong", "gyeonggi", "gangwon", "chungbuk", "chungnam", "jeonbuk", "gyeongbuk", "gyeongnam", "jeju"];
  for (const folder of existingRoots) {
    if (expectedRoots.has(folder) || folder === "gwangju" || folder === "jeonnam") {
      await rm(join(root, folder), { recursive: true, force: true });
    }
  }

  for (const region of regions) {
    for (const [areaSlug, areaName] of region.areas) {
      const output = areaSlug
        ? join(root, region.slug, areaSlug, "index.html")
        : join(root, region.slug, "index.html");
      await mkdir(dirname(output), { recursive: true });
      await writeFile(output, page(region, areaSlug, areaName), "utf8");

      const children = subAreas[`${region.slug}/${areaSlug}`];
      if (children) {
        for (const [childSlug, childName] of children) {
          const childOutput = join(root, region.slug, areaSlug, childSlug, "index.html");
          await mkdir(dirname(childOutput), { recursive: true });
          await writeFile(childOutput, page(region, childSlug, childName, {
            slug: areaSlug,
            name: areaName,
            areas: children,
          }), "utf8");
        }
      }
    }
  }

  await rm(join(root, "subjects"), { recursive: true, force: true });
  for (const subject of subjects) {
    const output = join(root, "subjects", subject.slug, "index.html");
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, subjectPage(subject), "utf8");
  }

  const indexPath = join(root, "index.html");
  const index = await readFile(indexPath, "utf8");
  const replacement = homeDirectory();
  const sectionPattern = /    <!-- LOCATION_DIRECTORY_START -->[\s\S]*?    <!-- LOCATION_DIRECTORY_END -->|    <section class="areas" id="areas">[\s\S]*?    <\/section>/;
  if (!sectionPattern.test(index)) throw new Error("Homepage area section not found");
  await writeFile(indexPath, index.replace(sectionPattern, replacement), "utf8");

  const urls = regions.flatMap((region) => region.areas.flatMap(([slug]) => {
    const parentPath = pathFor(region, slug);
    const children = subAreas[`${region.slug}/${slug}`] ?? [];
    return [parentPath, ...children.map(([childSlug]) => `${parentPath}${childSlug}/`)];
  }));
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>https://passtutor.kr/</loc>
    <lastmod>${updatedAt}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
  </url>
${subjects.map(({ slug }) => `  <url><loc>${site}${subjectPath(slug)}</loc><lastmod>${updatedAt}</lastmod><changefreq>monthly</changefreq><priority>0.9</priority></url>`).join("\n")}
${urls.map((url) => `  <url><loc>https://passtutor.kr${url}</loc><lastmod>${updatedAt}</lastmod><priority>0.8</priority></url>`).join("\n")}
</urlset>
`;
  await writeFile(join(root, "sitemap.xml"), sitemap, "utf8");

  // 네이버 서치어드바이저 RSS 제출용 피드
  const pubDate = new Date(`${updatedAt}T09:00:00+09:00`).toUTCString();
  const rssItem = (title, path, description) => `    <item>
      <title>${title}</title>
      <link>${site}${path}</link>
      <guid>${site}${path}</guid>
      <description>${escapeHtml(description)}</description>
      <pubDate>${pubDate}</pubDate>
    </item>`;
  const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
  <channel>
    <title>에듀패스 | 공무원 공기업 자격증 1:1 화상과외</title>
    <link>${site}/</link>
    <description>9급·7급 공무원, NCS·인적성, 경제·회계 자격증, 취업영어 실시간 1:1 화상과외 안내</description>
    <language>ko</language>
    <lastBuildDate>${pubDate}</lastBuildDate>
${subjects.map((subject) => rssItem(subject.title, subjectPath(subject.slug), subject.description)).join("\n")}
  </channel>
</rss>
`;
  await writeFile(join(root, "rss.xml"), rss, "utf8");

  const subAreaCount = Object.values(subAreas).reduce((total, areas) => total + areas.length, 0);
  console.log(`Generated ${urls.length} location pages, including ${subAreaCount} general districts, and ${subjects.length} subject pages.`);
}

await generate();
